const DOC_ICONS = new Map<string, typeof FileText>(
  Object.entries(ICONS).map(([name, icon]) => [name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase(), icon]),
)

// Ikon dirender di server dan dikirim sebagai SVG jadi, sehingga peta ikon di atas
// tidak ikut masuk bundle browser. Hanya ikon yang dipakai sidebar yang dikirim.
export function renderDocIcons(sections: DocumentationNavSection[]): DocIcons {
  const icons: DocIcons = {}
  for (const item of sections.flatMap((section) => section.items)) {
    const Icon = DOC_ICONS.get(item.icon)
    if (Icon && !(item.icon in icons)) icons[item.icon] = <Icon className="size-4" aria-hidden="true" />
  }
  return icons
}
